void projectF(float latDeg, float lonDeg, float* x, float* y) {
  const float lonRad = lonDeg * 0.017453293f;
  const float latRad = latDeg * 0.017453293f;
  const float mercY  = logf(tanf(0.785398163f + latRad * 0.5f));
  *x = OFFSET_X + (lonRad - LON_MIN_RAD) * SCALE;
  *y = OFFSET_Y + (MERC_Y_MAX - mercY) * SCALE;
}

void project(float latDeg, float lonDeg, int16_t* x, int16_t* y) {
  float fx, fy;
  projectF(latDeg, lonDeg, &fx, &fy);
  *x = (int16_t)floorf(fx);
  *y = (int16_t)floorf(fy);
}

